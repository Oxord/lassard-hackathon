"""Raster assets for the deck: plan crops with the glass label, QR code, placeholders.

plan/*.png stay untouched: slides use derived copies in output/assets/slide-*.png
without the source title and footnotes, with the label «стекло в цех» drawn into
the image so HTML and PDF show the same thing.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# Same palette as scripts/make_infographics.py: slides and graphics share one set of colours.
RED = '#DD191C'
INK = '#4A4A4A'
MID = '#7F7F7F'
LIGHT = '#E7E6E6'
PALE = '#F5F5F5'
WHITE = '#FFFFFF'

# Pixel boxes in plan/plan-*.png (1512 px wide, generated by plan/make_plan.py).
ROOM_BOX = (0, 60, 1546, 845)          # axes, room, south glass line and the plan legend
OWN_GLASS_NOTE = (180, 705, 545, 750)    # plan's own glass caption under axes A–B, crop coordinates: replaced by GLASS_LABEL
ENTRY_LABELS = ((0, 418, 153, 446), (158, 418, 275, 446), (1270, 418, 1384, 446), (1389, 418, 1546, 446))   # «Предлагаемый вход» west / «выход» east, both sides of the door bars, crop coordinates
ENTRY_GREEN_MARGIN = 12               # a caption pixel is greener than red/blue by more than this; red route and grey stay
PLAN_BG = (247, 247, 247)             # BG in plan/make_plan.py
LEGEND_BOTTOM = 850                    # flows plan: legend with the role-route row ends at y 849; a footnote tail follows
LEGEND_LEFT = 1160                    # footnotes left of this x are cut off below ROOM_BOX
NORTH_NOTE = (500, 62, 1050, 88)       # note on the north wall, crop coordinates
GLASS_LABEL = '▲  СМОТРОВОЕ СТЕКЛО 12×3 м (оси A–B) — финал луча'


def font(font_dir, size, bold=False):
    return ImageFont.truetype(str(Path(font_dir) / ('arialbd.ttf' if bold else 'arial.ttf')), size)


def placeholder(path, label, size, font_dir):
    """Grey stand-in for a missing asset; the label says what has to be supplied."""
    path.parent.mkdir(parents=True, exist_ok=True)
    w, h = size
    image = Image.new('RGB', size, PALE)
    draw = ImageDraw.Draw(image)
    draw.rectangle((2, 2, w - 3, h - 3), outline=MID, width=4)
    big = font(font_dir, max(14, h // 5), True)
    small = font(font_dir, max(10, h // 9))
    draw.text((w / 2, h / 2 - h * .08), label.upper(), fill=INK, font=big, anchor='mm')
    draw.text((w / 2, h / 2 + h * .22), 'заглушка', fill=MID, font=small, anchor='mm')
    image.save(path)


def asset_or_placeholder(assets, name, label, size, font_dir):
    """Return the asset name to use: the real file if present, else a generated placeholder."""
    if (assets / name).exists():
        return name
    stand_in = f'placeholders/{Path(name).stem}.png'
    placeholder(assets / stand_in, label, size, font_dir)
    print(f'Placeholder: {name} -> {stand_in}')
    return stand_in


def _erase_entry_labels(room):
    """Remove the green entrance captions; door bars sit between the boxes, the red route crossing them stays."""
    pixels = room.load()
    for x0, y0, x1, y1 in ENTRY_LABELS:
        for x in range(x0, x1):
            for y in range(y0, y1):
                r, g, b = pixels[x, y]
                if g - max(r, b) > ENTRY_GREEN_MARGIN:
                    pixels[x, y] = PLAN_BG if x >= 158 and x < 1384 else (255, 255, 255)


def plan_slide(src, dst, font_dir, legend=False):  # legend: the plan has a third legend row below ROOM_BOX
    """Crop a plan to the room, relabel entrances and add the glass label."""
    source = Image.open(src).convert('RGB')
    box = ROOM_BOX
    if legend:  # three-row legend reaches y 849; footnotes start at y 848 left of it
        box = (*ROOM_BOX[:3], LEGEND_BOTTOM)
    room = source.crop(box)
    if legend:
        ImageDraw.Draw(room).rectangle((0, ROOM_BOX[3] - box[1], LEGEND_LEFT, LEGEND_BOTTOM - box[1]), fill=WHITE)
    _erase_entry_labels(room)
    draw = ImageDraw.Draw(room)
    draw.rectangle(NORTH_NOTE, fill=WHITE)
    draw.rectangle(OWN_GLASS_NOTE, fill=WHITE)
    label_font = font(font_dir, 26, True)
    draw.text((146, 431), 'Вход', fill=INK, font=label_font, anchor='rm')
    draw.text((1393, 431), 'Выход', fill=INK, font=label_font, anchor='lm')
    parts = [room]
    glass = Image.new('RGB', (ROOM_BOX[2], 64), WHITE)
    ImageDraw.Draw(glass).text((155, 30), GLASS_LABEL, fill=RED, font=font(font_dir, 32, True), anchor='lm')
    parts.append(glass)
    out = Image.new('RGB', (ROOM_BOX[2], sum(p.height for p in parts)), WHITE)
    y = 0
    for part in parts:
        out.paste(part, (0, y))
        y += part.height
    out.save(dst)


def qr_code(url, dst):
    """QR code to the public model; False when the qrcode package is missing."""
    try:
        import qrcode
    except ImportError:
        return False
    qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=16, border=2)
    qr.add_data(url)
    qr.make(fit=True)
    qr.make_image(fill_color=INK, back_color=WHITE).convert('RGB').save(dst)
    return True
